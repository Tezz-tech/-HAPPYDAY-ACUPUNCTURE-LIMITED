// Builds the 针灸 (zhēnjiǔ) glyph outlines used by the Seal component.
// The glyphs come from Noto Sans SC (SIL OFL) via Google Fonts, subset to the two characters.
// They are converted to plain SVG path data, so no CJK font is loaded on the site (docs/02 §4).
// Re-run only if the seal artwork changes: node web/scripts/build-seal-glyphs.js
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as fontkit from 'fontkit';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../app/components/brand/seal-glyphs.generated.js');
const TEXT = '针灸';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

async function fetchFont() {
  const cssUrl = `https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@500&text=${encodeURIComponent(TEXT)}`;
  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': UA } })).text();
  const match = css.match(/url\((https:[^)]+)\)/);
  if (!match) throw new Error('Could not find the woff2 URL for the seal glyphs');
  const res = await fetch(match[1]);
  return Buffer.from(await res.arrayBuffer());
}

/**
 * Places one glyph inside a box of `size` units, with its baseline at `bottom`.
 * @param {any} glyph
 * @param {number} x left edge
 * @param {number} bottom baseline position in viewBox units
 * @param {number} s scale (font units to viewBox units)
 */
function placed(glyph, x, bottom, s) {
  const b = glyph.path.bbox;
  const dx = x - b.minX * s;
  const dy = bottom + b.minY * s; // font y grows upward; the SVG y axis grows downward
  return glyph.path.transform(s, 0, 0, -s, dx, dy).toSVG();
}

async function main() {
  const font = fontkit.create(await fetchFont());
  const s = 0.042;
  const zhen = font.glyphForCodePoint(TEXT.codePointAt(0));
  const jiu = font.glyphForCodePoint(TEXT.codePointAt(1));
  const bottom = 70;
  const body = [
    '// Generated by web/scripts/build-seal-glyphs.js from Noto Sans SC (SIL OFL). Do not edit.',
    `export const SEAL_GLYPH_ZHEN = ${JSON.stringify(placed(zhen, 14, bottom, s))};`,
    `export const SEAL_GLYPH_JIU = ${JSON.stringify(placed(jiu, 52, bottom, s))};`,
    '',
  ].join('\n');
  await writeFile(out, body);
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
