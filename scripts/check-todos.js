// Scans /content JSON and the code for TODO_CLIENT and rewrites TODO_CLIENT.md.
// Every TODO_CLIENT string in /content is listed, so nothing is silently missed.
import { readFile, readdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MARK = 'TODO_CLIENT';

/** Words that make a gap launch-blocking (sorted to the top of the list). */
const BLOCKING =
  /price|duration|deposit|hours|timezone|email|address|geo|googleMaps|directions|cacRc|cancellation|bank|payments|mode|capacity|portrait|bio|qualification|alsoAccepted|servicesBeyond|appointmentTypes|_confirm|legal/i;

/**
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
async function walk(dir, exts) {
  const out = [];
  for (const entry of await readdir(dir)) {
    const full = path.join(dir, entry);
    const info = await stat(full);
    if (info.isDirectory()) {
      if (['node_modules', 'build', 'dist', '.react-router'].includes(entry)) continue;
      out.push(...(await walk(full, exts)));
    } else if (exts.some((e) => entry.endsWith(e))) {
      out.push(full);
    }
  }
  return out;
}

/**
 * Collects TODO_CLIENT strings from a parsed JSON value.
 * @param {unknown} value
 * @param {string} at
 * @param {{ at: string, text: string }[]} acc
 */
function collect(value, at, acc) {
  if (typeof value === 'string') {
    if (value.includes(MARK)) acc.push({ at, text: value });
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => collect(v, `${at}[${i}]`, acc));
  } else if (value && typeof value === 'object') {
    for (const [k, v] of Object.entries(value)) collect(v, at ? `${at}.${k}` : k, acc);
  }
}

async function main() {
  /** @type {{ file: string, at: string, text: string, blocking: boolean }[]} */
  const items = [];

  for (const file of await walk(path.join(root, 'content'), ['.json'])) {
    const rel = path.relative(root, file).replaceAll('\\', '/');
    const found = [];
    collect(JSON.parse(await readFile(file, 'utf8')), '', found);
    for (const f of found) items.push({ file: rel, at: f.at, text: f.text, blocking: BLOCKING.test(f.at) });
  }

  for (const file of await walk(path.join(root, 'web', 'app'), ['.js', '.jsx'])) {
    const rel = path.relative(root, file).replaceAll('\\', '/');
    const lines = (await readFile(file, 'utf8')).split('\n');
    lines.forEach((line, i) => {
      if (line.includes(MARK))
        items.push({ file: `${rel}:${i + 1}`, at: 'code', text: line.trim(), blocking: false });
    });
  }

  items.sort((a, b) => Number(b.blocking) - Number(a.blocking) || a.file.localeCompare(b.file));

  const rows = items.map(
    (i, n) =>
      `| ${n + 1} | ${i.blocking ? 'Launch-blocking' : 'Before launch'} | \`${i.file}\` | \`${i.at}\` | ${i.text.replaceAll('|', '\\|')} |`,
  );

  const md = [
    '# TODO_CLIENT',
    '',
    'Gaps the client must answer before launch. Generated by `npm run check:todos`. Do not edit by hand.',
    '',
    `Total: ${items.length} (${items.filter((i) => i.blocking).length} launch-blocking).`,
    '',
    '| # | Priority | Source | Field | What is needed |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');

  await writeFile(path.join(root, 'TODO_CLIENT.md'), md);
  console.log(
    `TODO_CLIENT.md: ${items.length} items (${items.filter((i) => i.blocking).length} launch-blocking)`,
  );
  if (items.length === 0) console.warn('warning: no TODO_CLIENT items found');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
