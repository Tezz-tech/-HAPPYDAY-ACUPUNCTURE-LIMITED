// Copies brand and photo assets into web/public and generates LQIP placeholders.
// Run automatically before web dev/build (see web/package.json).
import { cp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'assets');
const publicDir = path.join(root, 'web', 'public');
const lqipOut = path.join(root, 'web', 'app', 'content', 'photos.generated.js');

/** Brand files served from the site root (favicons, app icons). */
const brandRootFiles = [
  'favicon.svg',
  'favicon-32.png',
  'apple-touch-icon.png',
  'icon-192.png',
  'icon-512.png',
];

async function main() {
  await mkdir(path.join(publicDir, 'brand'), { recursive: true });
  await rm(path.join(publicDir, 'photos'), { recursive: true, force: true });
  await cp(path.join(assets, 'photos'), path.join(publicDir, 'photos'), {
    recursive: true,
    filter: (src) => !src.endsWith('manifest.json'),
  });
  await cp(path.join(assets, 'brand'), path.join(publicDir, 'brand'), { recursive: true });
  for (const file of brandRootFiles) {
    const from = path.join(assets, 'brand', file);
    if (existsSync(from)) await cp(from, path.join(publicDir, file));
  }

  const manifest = JSON.parse(await readFile(path.join(assets, 'photos', 'manifest.json'), 'utf8'));
  /** @type {Record<string, string>} */
  const lqip = {};
  /** @type {Record<string, object>} */
  const photos = {};
  for (const photo of manifest.photos) {
    const src = path.join(assets, 'photos', photo.files.jpg);
    const buf = await sharp(src).resize(16).blur(1).jpeg({ quality: 40 }).toBuffer();
    lqip[photo.id] = `data:image/jpeg;base64,${buf.toString('base64')}`;
    const { notes: _notes, ...rest } = photo;
    photos[photo.id] = rest;
  }

  const body = [
    '// Generated by scripts/sync-assets.js from assets/photos/manifest.json. Do not edit.',
    `export const PHOTOS = ${JSON.stringify(photos, null, 2)};`,
    `export const LQIP = ${JSON.stringify(lqip, null, 2)};`,
    '',
  ].join('\n');
  await writeFile(lqipOut, body);
  console.log(`synced ${Object.keys(lqip).length} photos, wrote PHOTOS and LQIP to ${path.relative(root, lqipOut)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
